"""Write a TensorRT plugin from a Triton kernel plus a small spec.

The hand-written `AddScalarTritonPlugin.cu` is ~330 lines of which about six are about the kernel;
everything else follows mechanically from "one input, one output, same shape, FP32, elementwise".
That is what this file automates, and it is the reason a generator is worth having: the boilerplate
is not just long, it is the part that goes wrong silently (a missing `setLoggerFinder`, a forgotten
`double` -> `float` patch).

The generator also does something the hand-written plugin cannot do conveniently: it AOT-compiles
the **same kernel several times** with different `BLOCK_SIZE` / `num_warps`, links them into one
dispatcher, and exposes each specialization as a TensorRT **tactic**. TensorRT then times them
during the build and bakes the winner into the engine -- Triton autotuning done by the TensorRT
builder, with no autotuner at run time.

Scope, stated honestly: this handles element-wise kernels shaped
`kernel(in0_ptr, ..., out_ptr, <float attributes>, n_element, BLOCK_SIZE: constexpr)` over FP32.
That is enough for both operators here and small enough to read; anything else (multiple outputs,
shape changes, other dtypes) needs the spec and the templates extended.
"""

