MAKEFILE_TEMPLATE = """TRT_COOKBOOK_PATH ?= {cookbook_path}
include $(TRT_COOKBOOK_PATH)/include/Makefile.inc
LDFLAG += -lcuda

# GENERATED by plugin_gen.py -- do not edit.
all: {plugin_name}Plugin.so

{plugin_name}Plugin.o: {plugin_name}Plugin.cu {plugin_name}Plugin.h {stem}.h
\t$(COMMAND_O)

{stem}.o: {stem}.c
\t$(NVCC) -x c -O3 -Xcompiler -fPIC -I$(CUDA_PATH)/include -o $@ -c $<

{variant_object_rule}
{plugin_name}Plugin.so: {plugin_name}Plugin.o cookbookHelper.o {stem}.o {variant_object}
\t$(COMMAND_SO)
"""

def compile_kernel_variants(spec, output_path: Path):
    """Run `triton.tools.compile` once per variant, link them, and patch the fp32 ABI bug.

    Returns the list of per-variant `.c` files, in the order the linker will see them -- that order
    is the `algo_id` order, hence the tactic order.
    """
    stem = spec["stem"]
    header_list = []
    for variant in spec["variant_list"]:
        command = [
            "python3",
            "-m",
            "triton.tools.compile",
            str(current_path / spec["kernel_file"]),
            "--kernel-name",
            spec["kernel_name"],
            "--out-name",
            stem,
            "-o",
            str(output_path / stem),
            "--num-warps",
            str(variant["num_warps"]),
            "--signature",
            spec["signature"].format(**variant),
            "--grid",
            spec["grid"].format(**variant),
        ]
        subprocess.run(command, check=True, capture_output=True)
    # `link` sorts by the header names it is given; sort them so the tactic order is reproducible
    header_list = sorted(output_path.glob(f"{stem}.*.h"))
    subprocess.run(["python3", "-m", "triton.tools.link", *[str(p) for p in header_list], "-o", str(output_path / stem)], check=True, capture_output=True)

    # The fp32 ABI patch, applied to every generated file. `triton.tools.compile` declares an `fp32`
    # kernel argument as `double` in C and then hands `&arg` to `cuLaunchKernel`, whose parameter
    # slot is 4 bytes wide -> the kernel reads the low half of the double. See README.md.
    for attribute in spec["attribute_list"]:
        for path in list(output_path.glob(f"{stem}*.c")) + list(output_path.glob(f"{stem}*.h")):
            path.write_text(re.sub(rf"\bdouble {attribute}\b", f"float {attribute}", path.read_text()))
    return sorted(output_path.glob(f"{stem}.*.c"))

def generate(spec, b_verbose: bool = True) -> Path:
    """Emit, compile and link a complete plugin. Returns the path of the `.so`."""
    # One directory per plugin: two generated plugins must be able to coexist, and wiping a shared
    # directory would delete a `.so` TensorRT still has open.
    output_path = current_path / "generated" / spec["plugin_name"]
    shutil.rmtree(output_path, ignore_errors=True)
    output_path.mkdir(parents=True, exist_ok=True)

    variant_source_list = compile_kernel_variants(spec, output_path)
    assert len(variant_source_list) == len(spec["variant_list"]), \
        f"{len(spec['variant_list'])} variants asked for but {len(variant_source_list)} compiled: two variants collided into one cubin"

    plugin_name = spec["plugin_name"]
    attribute_list = spec["attribute_list"]
    substitution = dict(
        plugin_name=plugin_name,
        class_name=f"{plugin_name}Plugin",
        stem=spec["stem"],
        kernel_name=spec["kernel_name"],
        kernel_file=spec["kernel_file"],
        n_input=spec["n_input"],
        n_tactic=len(spec["variant_list"]),
        variant_comment=", ".join(f"BLOCK_SIZE={v['block_size']}/num_warps={v['num_warps']}" for v in spec["variant_list"]),
        member_declaration="".join(f"    float                    m_{a} {{0.0f}};\n" for a in attribute_list),
        constructor_parameter=", ".join(f"float const {a}" for a in attribute_list) if attribute_list else "",
        constructor_initializer=(":\n    " + ", ".join(f"m_{a}({a})" for a in attribute_list)) if attribute_list else "",
        constructor_argument=", ".join(attribute_list),
        call_argument=", ".join(["stream"] + [f"reinterpret_cast<CUdeviceptr>(inputs[{i}])" for i in range(spec["n_input"])] + ["reinterpret_cast<CUdeviceptr>(outputs[0])"] + [f"m_{a}" for a in attribute_list] + ["static_cast<int32_t>(nElement64)"]),
        serialize_body="".join(f'        mDataToSerialize.emplace_back(PluginField("{a}", &m_{a}, PluginFieldType::kFLOAT32, 1));\n' for a in attribute_list),
        attribute_body="".join(f'    mPluginAttributes.emplace_back(PluginField("{a}", nullptr, PluginFieldType::kFLOAT32, 1));\n' for a in attribute_list),
        parse_body="".join(f"""        float {a} {{0.f}};
        for (int32_t i = 0; fc != nullptr && fc->fields != nullptr && i < fc->nbFields; ++i)
        {{
            if (fc->fields[i].name != nullptr && std::strcmp(fc->fields[i].name, "{a}") == 0 && fc->fields[i].data != nullptr)
            {{
                {a} = *static_cast<float const *>(fc->fields[i].data);
            }}
        }}
""" for a in attribute_list),
    )

    (output_path / f"{plugin_name}Plugin.h").write_text(HEADER_TEMPLATE.format(**substitution))
    (output_path / f"{plugin_name}Plugin.cu").write_text(SOURCE_TEMPLATE.format(**substitution))
    variant_object = " ".join(p.with_suffix(".o").name for p in variant_source_list)
    (output_path / "Makefile").write_text(MAKEFILE_TEMPLATE.format(
        cookbook_path=current_path.parent.parent,
        plugin_name=plugin_name,
        stem=spec["stem"],
        variant_object=variant_object,
        variant_object_rule="\n".join(f"{p.with_suffix('.o').name}: {p.name}\n\t$(NVCC) -x c -O3 -Xcompiler -fPIC -I$(CUDA_PATH)/include -o $@ -c $<\n" for p in variant_source_list),
    ))

    subprocess.run(["make", "all", "-j"], cwd=output_path, check=True, capture_output=True)
    if b_verbose:
        line_count = sum(len((output_path / f"{plugin_name}Plugin{suffix}").read_text().splitlines()) for suffix in [".h", ".cu"])
        print(f"    generated {line_count} lines of C++ for {plugin_name} from a {len(spec)}-key spec, "
              f"{len(spec['variant_list'])} AOT variants -> {len(spec['variant_list'])} TensorRT tactics")
    return output_path / f"{plugin_name}Plugin.so"

# The spec for a second, different operator: no attribute, different argument list, three variants.
GELU_SPEC = dict(
    plugin_name="GeluTriton",
    kernel_file="kernel.py",
    kernel_name="gelu_kernel",
    stem="gelu",
    n_input=1,
    attribute_list=[],
    signature="*fp32:16, *fp32:16, i32, {block_size}",
    grid="(n_element + {block_size} - 1) / {block_size}, 1, 1",
    variant_list=[
        dict(block_size=128, num_warps=1),
        dict(block_size=1024, num_warps=4),
        dict(block_size=4096, num_warps=8),
    ],
)

if __name__ == "__main__":
    print(generate(GELU_SPEC))
