bool AddScalarTritonPlugin::supportsFormatCombination(int32_t pos, DynamicPluginTensorDesc const *inOut, int32_t nbInputs, int32_t nbOutputs) noexcept
{
    WHERE_AM_I();
    if (inOut == nullptr || nbInputs != 1 || nbOutputs != 1 || pos < 0 || pos >= nbInputs + nbOutputs)
    {
        return false;
    }

    bool res {false};
    switch (pos)
    {
    case 0:
        // The kernel was compiled for `*fp32`, so only FP32 linear can be accepted. A Triton kernel
        // is specialized per dtype at AOT time: supporting FP16 too means compiling a second
        // variant, it is not a run-time decision.
        res = inOut[0].desc.type == DataType::kFLOAT && inOut[0].desc.format == TensorFormat::kLINEAR;
        break;
    case 1:
        res = inOut[1].desc.type == inOut[0].desc.type && inOut[1].desc.format == inOut[0].desc.format;
        break;
    default: // should NOT be here!
        break;
    }
    PRINT_FORMAT_COMBINATION();
    return res;
}

