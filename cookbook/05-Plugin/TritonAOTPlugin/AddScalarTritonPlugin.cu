int32_t AddScalarTritonPlugin::onShapeChange(PluginTensorDesc const *in, int32_t nbInputs, PluginTensorDesc const *out, int32_t nbOutputs) noexcept
{
    WHERE_AM_I();
    if (in == nullptr || out == nullptr || nbInputs != 1 || nbOutputs != 1)
    {
        return -1;
    }
    for (int32_t i = 0; i < in[0].dims.nbDims; ++i)
    {
        if (in[0].dims.d[i] <= 0)
        {
            return -1;
        }
    }
    return 0;
}

int32_t AddScalarTritonPlugin::enqueue(PluginTensorDesc const *inputDesc, PluginTensorDesc const *outputDesc, void const *const *inputs, void *const *outputs, void *workspace, cudaStream_t stream) noexcept
{
    WHERE_AM_I();
    if (inputDesc == nullptr || outputDesc == nullptr || inputs == nullptr || outputs == nullptr || inputs[0] == nullptr || outputs[0] == nullptr)
    {
        return -1;
    }
    if (inputDesc[0].type != DataType::kFLOAT || outputDesc[0].type != DataType::kFLOAT)
    {
        return -1;
    }

    int64_t nElement64 {1};
    for (int32_t i = 0; i < inputDesc[0].dims.nbDims; ++i)
    {
        int32_t const dim = inputDesc[0].dims.d[i];
        nElement64 *= dim;
        if (dim <= 0 || nElement64 > std::numeric_limits<int32_t>::max())
        {
            return -1;
        }
    }

    // The whole point of the example: one call, no Triton, no Python, no JIT. The cubin is a byte
    // array inside this `.so` and the launcher is the generated `cuLaunchKernel` wrapper.
    // The return value must be checked: the linked dispatcher rejects unaligned pointers with
    // CUDA_ERROR_INVALID_VALUE *without launching anything*, which would otherwise leave the output
    // buffer untouched and look like a wrong kernel rather than a failed launch.
    CUresult const ret = add_scalar_default(stream, reinterpret_cast<CUdeviceptr>(inputs[0]), reinterpret_cast<CUdeviceptr>(outputs[0]), mScalar, static_cast<int32_t>(nElement64));
    if (ret != CUDA_SUCCESS)
    {
        return -1;
    }

    return (cudaGetLastError() == cudaSuccess) ? 0 : -1;
}

IPluginV3 *AddScalarTritonPlugin::attachToContext(IPluginResourceContext *context) noexcept
{
    WHERE_AM_I();
    try
    {
        // Load the cubin here rather than letting the generated launcher do it lazily on the first
        // `enqueue`: `cuModuleLoadData` binds to whatever CUDA context is current, and this is the
        // moment TensorRT hands over the context the engine will actually run in.
        load_add_scalar();
        return clone();
    }
    catch (...)
    {
        return nullptr;
    }
}

