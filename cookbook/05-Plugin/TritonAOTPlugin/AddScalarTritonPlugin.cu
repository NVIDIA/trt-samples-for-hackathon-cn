// The ahead-of-time compiled Triton kernel. `add_scalar.h` is generated by the Makefile
// (`triton.tools.compile` then `triton.tools.link`) and is plain C without an `extern "C"` guard of
// its own, so the wrapper here is mandatory -- without it the link fails with an undefined
// reference to the C++-mangled name.
extern "C"
{
#include "add_scalar.h"
}

// A plugin library must export **both** `getCreators` and `setLoggerFinder`. Exporting only
// `getCreators` is not a link error and not a load error either: `loadLibrary` returns a handle and
// the creators are simply never registered, so the failure surfaces much later as
// "Cannot find plugin: AddScalarTriton, version: 1".
extern "C" void setLoggerFinder(nvinfer1::ILoggerFinder *finder) {}

